export async function POST(request: NextRequest) {
  try {
    const session = await getServerSession(authOptions)

    if (!session?.user?.id) {
      return NextResponse.json(
        { error: 'Unauthorized' },
        { status: 401 }
      )
    }

    const body = await request.json() as PatternGenerationRequest

    if (!body.description || !body.difficulty || !body.category) {
      return NextResponse.json(
        { error: 'Missing required fields' },
        { status: 400 }
      )
    }

    // Generate pattern with AI (placeholder)
    const generatedPattern = await generatePatternWithAI(body)

    // Save to database
    const pattern = await prisma.pattern.create({
      data: {
        title: generatedPattern.title,
        description: generatedPattern.description,
        difficulty: body.difficulty,
        category: body.category,
        materials: generatedPattern.materials,
        hookSize: generatedPattern.hookSize,
        gaugeInfo: generatedPattern.gaugeInfo,
        instructions: generatedPattern.instructions,
        estimatedTime: generatedPattern.estimatedTime,
        aiGenerated: true,
        isPublic: false, // User can choose to make it public later
        authorId: session.user.id,
      },
    })

    return NextResponse.json(
      {
        success: true,
        pattern: {
          id: pattern.id,
          title: pattern.title,
        },
      },
      { status: 201 }
    )
  } catch (error) {
    console.error('Pattern generation error:', error)
    return NextResponse.json(
      { error: 'Internal server error' },
      { status: 500 }
    )
  }
}
